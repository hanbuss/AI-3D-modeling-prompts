def explode_for(group, direction):
    """按组给出爆炸位移：整体收在 4–9 m 内，爆炸图仍然成阵型。

    direction 传该零件"应往哪飞"的单位向量或 (dx,dy,dz) 粗方向；
    这里统一按组放大，保证同组零件方向一致、不漏。
    """
    scale = {
        "weapons": 1.00,
        "gear": 1.25,
        "canopy": 1.05,
        "engines": 1.10,
        "wings": 1.00,
        "hull_fore": 1.45,
        "hull_mid": 1.30,
        "hull_aft": 1.20,
        "detail": 1.15,
    }.get(group, 1.0)
    dx, dy, dz = direction
    n = math.sqrt(dx * dx + dy * dy + dz * dz) or 1.0
    return (dx / n * 4.2 * scale, dy / n * 4.2 * scale, dz / n * 4.2 * scale)


